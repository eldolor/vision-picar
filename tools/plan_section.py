# Git exports its repository-local variables (GIT_DIR and friends) to a
# hook, and every git command a child runs then acts on THIS repository,
# whatever its cwd. The pre-push hook runs the suite, and a test that builds
# a scratch repo in tmp_path (test_plan_section.py) re-initialised this one
# on 2026-10-09: core.bare=true, a "t" identity, a "base" commit on the
# branch being pushed, a stray branch. The list is git's own
# (`git rev-parse --local-env-vars`), less GIT_CONFIG_COUNT: with
# GIT_CONFIG_KEY_n/VALUE_n it carries config the environment itself
# injects (the cloud git proxy's), not a pointer to a repository.
_LOCAL_GIT_VARS_FALLBACK = (
    "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_CONFIG", "GIT_CONFIG_PARAMETERS",
    "GIT_OBJECT_DIRECTORY", "GIT_DIR", "GIT_WORK_TREE", "GIT_IMPLICIT_WORK_TREE",
    "GIT_GRAFT_FILE", "GIT_INDEX_FILE", "GIT_NO_REPLACE_OBJECTS",
    "GIT_REPLACE_REF_BASE", "GIT_PREFIX", "GIT_SHALLOW_FILE", "GIT_COMMON_DIR",
)
_KEEP_GIT_VARS = {"GIT_CONFIG_COUNT"}


def repo_local_git_vars() -> tuple:
    try:
        out = subprocess.run(["git", "rev-parse", "--local-env-vars"], cwd="/",
                             capture_output=True, text=True, timeout=10).stdout.split()
    except (OSError, subprocess.SubprocessError):
        out = []
    return tuple(v for v in (out or _LOCAL_GIT_VARS_FALLBACK) if v not in _KEEP_GIT_VARS)


def scrubbed_env() -> dict:
    """This process's environment, minus the variables that would point a
    child's git commands at this repository."""
    drop = set(repo_local_git_vars())
    return {k: v for k, v in os.environ.items() if k not in drop}


def usable_cores() -> int:
    """The cores this process may run on: its affinity, and a cgroup CPU
    quota under it if one is set (a container's or cloud session's limit,
    not the host's count)."""
    try:
        n = len(os.sched_getaffinity(0))
    except (AttributeError, OSError):          # macOS has no affinity call
        n = os.cpu_count() or 2
    try:
        quota, period = open("/sys/fs/cgroup/cpu.max").read().split()[:2]
        if quota != "max":
            n = min(n, max(1, int(quota) // int(period)))
    except (OSError, ValueError):
        pass
    return n


def worker_count() -> int:
    """How many pytest-xdist workers the fast tier runs on (3.121): half the
    usable cores -- never more (the desktop stopped dead on 2026-10-28 under
    hours of full-CPU load) -- or fewer by `PICAR_TEST_WORKERS`. 1 or less
    is serial."""
    half = max(1, usable_cores() // 2)
    asked = os.environ.get("PICAR_TEST_WORKERS", "").strip()
    if not asked:
        return half
    try:
        n = int(asked)
    except ValueError:
        print(f"fast tier: PICAR_TEST_WORKERS={asked!r} is not a number; using {half}",
              flush=True)
        return half
    if n > half:
        print(f"fast tier: PICAR_TEST_WORKERS={n} is over half the cores; using {half}",
              flush=True)
    return min(n, half)


def xdist_starts(py: str, root: str, load: list) -> bool:
    """Whether pytest under `py`, where and as the suite will run, can start
    an xdist worker: one worker collecting one small file. An import of
    xdist alone passes without execnet, or with the plugin turned off in
    PYTEST_ADDOPTS."""
    return subprocess.run([py, "-m", "pytest", "-q", "-p", "no:cacheprovider", *load,
                           "-n", "1", "--collect-only", "tests/test_plan_section.py"],
                          cwd=root, env=scrubbed_env(), capture_output=True).returncode == 0


def parallel_args(py: str, root: str) -> list:
    """The fast tier's xdist arguments (3.121), or [] -- serial, as before --
    when pytest cannot start xdist workers here or one worker is asked for.
    `--dist loadfile` keeps each test file whole on one worker, in its own
    order; only files run side by side. With plugin autoloading off, xdist
    is named."""
    n = worker_count()
    if n <= 1:
        return []
    load = ["-p", "xdist.plugin"] if os.environ.get("PYTEST_DISABLE_PLUGIN_AUTOLOAD") else []
    if not xdist_starts(py, root, load):
        print("fast tier: pytest cannot start xdist workers in this venv, so it runs "
              "serially (pip install -r requirements.txt)", flush=True)
        return []
    return [*load, "-n", str(n), "--dist", "loadfile"]


def run_tests(root: str, full: bool) -> bool:
    py = venv_python(root)
    # The full suite (`ready --full`, the nightly) stays serial: it holds the
    # browser and live-stack tests, timed alone.
    args = [] if full else [*SLOW_TESTS, *parallel_args(py, root)]
    return subprocess.run([py, "-m", "pytest", "tests/", "-q",
                           "-p", "no:cacheprovider", *args], cwd=root,
                          env=scrubbed_env()).returncode == 0


