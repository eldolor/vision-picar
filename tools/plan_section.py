"""
tools/plan_section.py -- one plan section per branch, so parallel Claude
sessions never collide (docs/guides/PARALLEL-SESSIONS.md).

    python tools/plan_section.py new <slug> "<title>"   reserve the next 3.N: branch + worktree + file
    python tools/plan_section.py env [3.N]              this branch's ports, ROS domain, container, image, logs
    python tools/plan_section.py index                  regenerate the section index
    python tools/plan_section.py overlap                files this branch shares with other plan/* branches
    python tools/plan_section.py ready [--full]         rebase check + fast tier (or the full suite); records a pass
    python tools/plan_section.py gate <base> <sha>      the pre-push hook's check: docs only -> spec lint, else fast tier
    python tools/plan_section.py reviewed [--thermos] [range]   record that the code commits in range
                                                        (default origin/dev..HEAD) were reviewed
    python tools/plan_section.py split                  one-time: PLAN-ros-alignment.md's 3.N sections -> files
    python tools/plan_section.py board [--all]          every open step: claimed, active, waiting, blocked or free
    python tools/plan_section.py next                   the first step this session may claim
    python tools/plan_section.py claim <step>           take a step for this session (tools/plan_claims.py)
    python tools/plan_section.py release [<step>]       give back this session's claims

Sections live in `docs/plans/ros-alignment/<number>-<slug>.md`; the number is
reserved by the BRANCH NAME `plan/<number>-<slug>`. Worktrees share one .git,
so every session on this machine sees every branch, pushed or not, and git
refuses to create a branch that exists -- which makes `new` atomic.
"""

import hashlib
import os
import re
import subprocess
import sys

PLAN = "docs/plans/PLAN-ros-alignment.md"
DIR = "docs/plans/ros-alignment"
INDEX = f"{DIR}/README.md"
HEAD_RE = re.compile(r"^### (3\.(\d+)([a-z]?)) (.*)$")
FILE_RE = re.compile(r"^(3\.(\d+)([a-z]?))-(.+)\.md$")
BRANCH_RE = re.compile(r"plan/(3\.(\d+))-")
SECTIONS_START = "<!-- sections: generated by tools/plan_section.py index; do not edit -->"
SECTIONS_END = "<!-- /sections -->"


def git(*args, check=True, cwd=None) -> str:
    r = subprocess.run(["git", *args], capture_output=True, text=True, cwd=cwd)
    if check and r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout.strip()


def top() -> str:
    return git("rev-parse", "--show-toplevel")


def common_dir(cwd=None) -> str:
    """The shared .git, absolute. Git prints it relative (`.git`, `../.git`)
    in the main checkout, which then names a different place from any other
    cwd (3.76 I7)."""
    return git("rev-parse", "--path-format=absolute", "--git-common-dir", cwd=cwd)


def main_checkout(cwd=None) -> str:
    """The main checkout, where every section's worktree lives -- never the
    current worktree, or `new` run from one nests the next inside it (I5)."""
    return os.path.dirname(common_dir(cwd))


def slugify(title: str) -> str:
    s = re.sub(r"`[^`]*`", lambda m: m.group(0)[1:-1], title.lower())
    s = re.sub(r"\(.*?\)", "", s)
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return "-".join(s.split("-")[:6]) or "section"


def sort_key(num: str):
    m = re.match(r"3\.(\d+)([a-z]?)", num)
    return (int(m.group(1)), m.group(2))


# ---------- the index ----------

def sections(root: str):
    """[(number, title, filename)] from the section files, in order."""
    out = []
    for f in os.listdir(os.path.join(root, DIR)):
        m = FILE_RE.match(f)
        if not m:
            continue
        with open(os.path.join(root, DIR, f)) as fh:
            first = fh.readline().strip()
        title = re.sub(r"^#+\s*3\.\d+[a-z]?\s*", "", first)
        out.append((m.group(1), title, f))
    return sorted(out, key=lambda s: sort_key(s[0]))


def write_index(root: str) -> None:
    rows = [f"| [{n}]({f}) | {t} |" for n, t, f in sections(root)]
    body = "\n".join([
        "# PLAN-ros-alignment.md, section 3 -- one file per section",
        "",
        "Generated by `python tools/plan_section.py index`; do not edit by hand.",
        "A citation such as \"`PLAN-ros-alignment.md` 3.18\" means the file",
        "numbered 3.18 here. New sections: `python tools/plan_section.py new`",
        "(`docs/guides/PARALLEL-SESSIONS.md`).",
        "",
        SECTIONS_START,
        "| Section | Title |",
        "|---|---|",
        *rows,
        SECTIONS_END,
        "",
    ])
    with open(os.path.join(root, INDEX), "w") as fh:
        fh.write(body)


def cmd_index() -> None:
    root = top()
    write_index(root)
    print(f"{INDEX}: {len(sections(root))} sections")


# ---------- the one-time split ----------

def cmd_split() -> None:
    root = top()
    path = os.path.join(root, PLAN)
    lines = open(path).read().split("\n")
    starts = [i for i, l in enumerate(lines) if HEAD_RE.match(l)]
    end = next(i for i, l in enumerate(lines) if l.startswith("## 4."))
    if not starts:
        raise SystemExit("no ### 3.N sections left to split")
    os.makedirs(os.path.join(root, DIR), exist_ok=True)
    for k, s in enumerate(starts):
        e = starts[k + 1] if k + 1 < len(starts) else end
        m = HEAD_RE.match(lines[s])
        num, title = m.group(1), m.group(4)
        body = lines[s + 1:e]
        while body and body[-1] == "":
            body.pop()
        text = "\n".join([f"# {num} {title}", "",
                          f"*`PLAN-ros-alignment.md` section {num}; index: [README.md](README.md).*",
                          *body, ""])
        with open(os.path.join(root, DIR, f"{num}-{slugify(title)}.md"), "w") as fh:
            fh.write(text)
    pointer = [
        "### The sections live one per file",
        "",
        "Since 2026-10-07 each `3.N` section is its own file in",
        "`docs/plans/ros-alignment/`, indexed by",
        "[`ros-alignment/README.md`](ros-alignment/README.md), so parallel sessions",
        "never edit the same file (`docs/guides/PARALLEL-SESSIONS.md`). A citation",
        "\"`PLAN-ros-alignment.md` 3.18\" means `ros-alignment/3.18-*.md`. Start a",
        "new section with `python tools/plan_section.py new <slug> \"<title>\"`.",
        "",
    ]
    lines = lines[:starts[0]] + pointer + lines[end:]
    open(path, "w").write("\n".join(lines))
    write_index(root)
    print(f"split {len(starts)} sections into {DIR}/")


# ---------- reserving a number ----------

def used_numbers(root: str) -> set:
    nums = set()
    for ref in ("origin/dev", "HEAD"):
        listing = git("ls-tree", "--name-only", f"{ref}:{DIR}", check=False, cwd=root)
        for f in listing.splitlines():
            m = FILE_RE.match(f)
            if m:
                nums.add(int(m.group(2)))
    for b in git("branch", "-a", "--format=%(refname:short)", cwd=root).splitlines():
        m = BRANCH_RE.search(b)
        if m:
            nums.add(int(m.group(2)))
    return nums


def cmd_new(slug: str, title: str) -> None:
    root = top()
    slug = slugify(slug)
    git("fetch", "-q", "origin", cwd=root)
    n = max(used_numbers(root) | {0}) + 1
    trees = os.path.join(main_checkout(root), ".claude", "worktrees")
    for _ in range(20):
        num = f"3.{n}"
        branch = f"plan/{num}-{slug}"
        wt = os.path.join(trees, f"plan-{num}")
        # The branch first, on its own: only one session can create it, so a
        # branch this call made is this call's to delete. `worktree add -b`
        # made it and THEN found the path taken, and the retry left it
        # holding 3.N a second time (3.76 I5).
        made = subprocess.run(["git", "branch", branch, "origin/dev"],
                              capture_output=True, text=True, cwd=root)
        if made.returncode:
            if "already exists" not in made.stderr:
                raise SystemExit(made.stderr.strip())
            n += 1                 # another session took it a moment ago
            continue
        r = subprocess.run(["git", "worktree", "add", "-q", wt, branch],
                           capture_output=True, text=True, cwd=root)
        if r.returncode == 0:
            break
        git("branch", "-D", branch, check=False, cwd=root)
        if "already exists" not in r.stderr:
            raise SystemExit(r.stderr.strip())
        n += 1                     # the path is another session's
    else:
        raise SystemExit("could not reserve a section number")
    with open(os.path.join(wt, DIR, f"{num}-{slug}.md"), "w") as fh:
        fh.write(f"# {num} {title}\n\n"
                 f"*`PLAN-ros-alignment.md` section {num}; index: [README.md](README.md).*\n\n"
                 "**Why.** \n\n"
                 "**Criteria (written before building; CLAUDE.md section 7):**\n\n1. \n")
    write_index(wt)
    git("add", DIR, cwd=wt)
    git("commit", "-q", "-m", f"{num} reserved: {title}", cwd=wt)
    print(f"reserved {num} on branch {branch}\nworktree: {wt}\n")
    print(env_text(num))


# ---------- per-branch resources ----------

def section_of_branch(root: str) -> str:
    m = BRANCH_RE.search(git("rev-parse", "--abbrev-ref", "HEAD", cwd=root))
    if not m:
        raise SystemExit("not on a plan/3.N-* branch: pass the section, e.g. `env 3.44`")
    return m.group(1)


def _minor(num: str) -> int:
    return int(num.split(".")[1].rstrip("abcdefghijklmnopqrstuvwxyz"))


def ros_domain(num: str) -> int:
    """The minor number itself (3.44 -> 44): ROS 2 domains above 101 can
    clash with Linux's ephemeral ports. 73 and 74 are the fixed domains
    older stacks use (demo_explore's default, 3.42's lidar stack). 3.100
    would land on 0, the domain of every stack started without one (3.76
    I8); it shares 100 with 3.73 instead, as everything past 3.99 wraps onto
    a section 100 older (3.101 is 3.1's; `env` warns, 3.107)."""
    minor = _minor(num) % 100
    return {73: 100, 74: 101, 0: 100}.get(minor, minor)


def resources(num: str) -> dict:
    """Everything a live stack can collide on, derived from the section
    number. Ports are 9000 + 10 x minor for every section (3.107: they
    wrapped at 100 before; 3.2376 is the last below the ephemeral range).
    The ROS domain must stay within 1-101, so past 3.99 it wraps onto the
    section 100 older, and `env` names an active section that shares it."""
    base = 9000 + 10 * _minor(num)
    if base + 5 >= 32768:
        raise SystemExit(f"section {num}: its ports would reach Linux's ephemeral range "
                         f"(32768+); extend tools/plan_section.py resources()")
    return {
        "PICAR_ROBOT_PORT": base, "PICAR_BRAIN_PORT": base + 1,
        "PICAR_BODY_PORT": base + 2, "PICAR_SENSOR_PORT": base + 3,
        "PICAR_SENSOR2_PORT": base + 4, "PICAR_BRIDGE_PORT": base + 5,
        "ROS_DOMAIN_ID": ros_domain(num),
        "PICAR_ROS_CONTAINER": f"picar-ros-{num.replace('.', '')}",
        "ROS_IMAGE": f"vision-picar-ros:plan-{num}",
        "EXPLORE_LOGDIR": f"/tmp/vision-picar-{num}",
        "PICAR_ROBOT_URL": f"http://127.0.0.1:{base}",
        "PICAR_BRAIN_URL": f"http://127.0.0.1:{base + 1}",
        "PICAR_BRIDGE_URL": f"http://127.0.0.1:{base + 5}",
    }


def active_sections(root: str) -> list:
    """The sections with a worktree on this machine (`git worktree list`),
    leaving out one git marks prunable (its folder is gone)."""
    out = git("worktree", "list", "--porcelain", check=False, cwd=root)
    found = []
    for block in out.split("\n\n"):
        lines = block.splitlines()
        if any(l.startswith("prunable") for l in lines):
            continue
        for line in lines:
            m = BRANCH_RE.search(line) if line.startswith("branch ") else None
            if m:
                found.append(m.group(1))
    return found


def env_text(num: str, others=None) -> str:
    r = resources(num)
    lines = [f'# section {num}: paste into your shell, or `eval "$(python tools/plan_section.py env)"`']
    if others is None:
        try:
            others = active_sections(top())
        except SystemExit:              # outside a checkout: `env 3.N` needs no git
            others = []
    for o in sorted(set(others) - {num}, key=sort_key):
        if ros_domain(o) == r["ROS_DOMAIN_ID"]:
            # 3.107: a comment, so `eval` still works.
            lines.append(f"# WARNING: section {o} has a worktree here and shares ROS domain "
                         f"{r['ROS_DOMAIN_ID']}: do not run both sections' stacks at once")
    lines += [f"export {k}={v}" for k, v in r.items()]
    lines.append(f"# build this branch's ROS image (never :latest): "
                 f"docker build -t {r['ROS_IMAGE']} service/slam && mkdir -p {r['EXPLORE_LOGDIR']}")
    return "\n".join(lines)


def cmd_env(num=None) -> None:
    print(env_text(num or section_of_branch(top())))


# ---------- overlap ----------

def changed(root: str, ref: str) -> set:
    base = git("merge-base", "origin/dev", ref, check=False, cwd=root)
    if not base:
        return set()
    return set(git("diff", "--name-only", base, ref, cwd=root).splitlines())


def cmd_overlap() -> None:
    root = top()
    git("fetch", "-q", "origin", cwd=root)
    me = git("rev-parse", "--abbrev-ref", "HEAD", cwd=root)
    mine = changed(root, "HEAD") - {INDEX}
    found = False
    for b in sorted(set(git("branch", "-a", "--format=%(refname:short)", cwd=root).splitlines())):
        if "plan/" not in b or b.endswith(me) or b == me:
            continue
        shared = sorted(mine & (changed(root, b) - {INDEX}))
        if shared:
            found = True
            print(f"{b}:\n  " + "\n  ".join(shared))
    if not found:
        print("no file this branch changes is changed on another plan/* branch")


